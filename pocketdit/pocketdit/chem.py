"""Parsing and featurisation of protein pockets and ligands.

Plain RDKit + numpy. Every function returns torch tensors with fixed dtypes so a complex
can be featurised once, cached with ``torch.save`` and loaded cheaply during training.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import torch
from rdkit import Chem
from rdkit.Chem import AllChem

# --------------------------------------------------------------------------------------
# Vocabularies. Anything not listed maps to the last index ("other / unknown").
# --------------------------------------------------------------------------------------
ELEMENTS = ["C", "N", "O", "S", "P", "F", "Cl", "Br", "I", "B", "Se", "Si"]
RESIDUES = [
    "ALA", "ARG", "ASN", "ASP", "CYS", "GLN", "GLU", "GLY", "HIS", "ILE",
    "LEU", "LYS", "MET", "PHE", "PRO", "SER", "THR", "TRP", "TYR", "VAL",
]  # fmt: skip
ATOM_NAMES = [
    "N", "CA", "C", "CB", "O", "CG", "CG1", "CG2", "OG", "OG1", "SG", "CD", "CD1", "CD2",
    "ND1", "ND2", "OD1", "OD2", "SD", "CE", "CE1", "CE2", "CE3", "NE", "NE1", "NE2", "OE1",
    "OE2", "CH2", "NH1", "NH2", "OH", "CZ", "CZ2", "CZ3", "NZ", "OXT",
]  # fmt: skip
# Protonation variants (ATOM records) and common modified residues (HETATM records).
RESIDUE_ALIASES = {"HID": "HIS", "HIE": "HIS", "HIP": "HIS", "HSD": "HIS", "HSE": "HIS", "CYX": "CYS"}
MODIFIED_RESIDUES = {"MSE": "MET", "SEP": "SER", "TPO": "THR", "PTR": "TYR", "CSO": "CYS", "HYP": "PRO"}
HYBRIDIZATIONS = [
    Chem.HybridizationType.SP,
    Chem.HybridizationType.SP2,
    Chem.HybridizationType.SP3,
    Chem.HybridizationType.SP3D,
    Chem.HybridizationType.SP3D2,
]
BOND_TYPES = {Chem.BondType.SINGLE: 1, Chem.BondType.DOUBLE: 2, Chem.BondType.TRIPLE: 3, Chem.BondType.AROMATIC: 4}
MAX_SPD = 8  # topological distances are clipped to MAX_SPD + 1 ("far or disconnected")

# Embedding table sizes, consumed by the model.
# ligand: element, degree, formal charge, hybridisation, aromatic, in ring, number of Hs
LIG_FEATURE_SIZES = (len(ELEMENTS) + 1, 6, 5, len(HYBRIDIZATIONS) + 1, 2, 2, 5)
# pocket: element, atom name, residue type
POCKET_FEATURE_SIZES = (len(ELEMENTS) + 1, len(ATOM_NAMES) + 1, len(RESIDUES) + 1)
NUM_BOND_TYPES = 6  # 0 = no bond, 1-4 as above, 5 = other
NUM_SPD = MAX_SPD + 2


def _index(vocab: list, item: object) -> int:
    return vocab.index(item) if item in vocab else len(vocab)


# --------------------------------------------------------------------------------------
# Ligand
# --------------------------------------------------------------------------------------
def load_ligand(path: str | Path) -> Chem.Mol:
    """Read the first molecule of an SDF/MOL2 file, without hydrogens, with a 3D conformer.

    If the file has no 3D coordinates, one conformer is embedded with ETKDG (stereo tags are
    respected), which is all inference needs: the pose itself is generated by the model.
    """
    path = Path(path)
    mol = None
    if path.suffix.lower() == ".sdf":
        mol = next(iter(Chem.SDMolSupplier(str(path), removeHs=False)), None)
        if mol is None and path.with_suffix(".mol2").exists():
            path = path.with_suffix(".mol2")
    if path.suffix.lower() == ".mol2":
        mol = Chem.MolFromMol2File(str(path), removeHs=False)
    if mol is None:
        raise ValueError(f"Could not parse a molecule from {path}")
    mol = Chem.RemoveHs(mol)
    if mol.GetNumConformers() == 0 or not _is_3d(mol):
        mol_h = Chem.AddHs(mol)
        if AllChem.EmbedMolecule(mol_h, randomSeed=0) != 0:
            raise ValueError(f"Could not embed a 3D conformer for {path}")
        mol = Chem.RemoveHs(mol_h)
    return mol


def _is_3d(mol: Chem.Mol) -> bool:
    pos = mol.GetConformer().GetPositions()
    return bool(np.abs(pos[:, 2]).max() > 1e-3)


def atom_features(atom: Chem.Atom) -> list[int]:
    return [
        _index(ELEMENTS, atom.GetSymbol()),
        min(atom.GetDegree(), 5),
        int(np.clip(atom.GetFormalCharge(), -2, 2)) + 2,
        _index(HYBRIDIZATIONS, atom.GetHybridization()),
        int(atom.GetIsAromatic()),
        int(atom.IsInRing()),
        min(atom.GetTotalNumHs(), 4),
    ]


def signed_volume(center: np.ndarray, a: np.ndarray, b: np.ndarray, c: np.ndarray) -> float:
    return float(np.dot(a - center, np.cross(b - center, c - center)))


def chirality_reference(mol: Chem.Mol, pos: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Reference handedness of every tetrahedral stereocentre.

    For each centre we store three neighbours (sorted by index) and the sign of their signed
    volume in ``pos``. The model gets ``sign * volume(x_t)``: positive means correct handedness.
    Using the sign of a real 3D pose avoids RDKit's CW/CCW neighbour-ordering conventions.
    Non-centres point at themselves with sign 0, which makes their feature exactly 0.
    """
    mol = Chem.Mol(mol)
    Chem.AssignStereochemistryFrom3D(mol)
    n = mol.GetNumAtoms()
    nbrs = np.tile(np.arange(n)[:, None], (1, 3))
    sign = np.zeros(n, dtype=np.float32)
    for idx, _ in Chem.FindMolChiralCenters(mol, includeUnassigned=False):
        nb = sorted(a.GetIdx() for a in mol.GetAtomWithIdx(idx).GetNeighbors())
        if len(nb) < 3:
            continue
        nbrs[idx] = nb[:3]
        sign[idx] = np.sign(signed_volume(pos[idx], pos[nb[0]], pos[nb[1]], pos[nb[2]]))
    return nbrs, sign


def featurize_ligand(mol: Chem.Mol) -> dict[str, torch.Tensor]:
    """Atom features, bond-type and shortest-path matrices, coordinates and chirality references."""
    n = mol.GetNumAtoms()
    pos = mol.GetConformer().GetPositions().astype(np.float32)
    feat = np.array([atom_features(a) for a in mol.GetAtoms()], dtype=np.int64)
    bond = np.zeros((n, n), dtype=np.int64)
    for b in mol.GetBonds():
        i, j = b.GetBeginAtomIdx(), b.GetEndAtomIdx()
        bond[i, j] = bond[j, i] = BOND_TYPES.get(b.GetBondType(), 5)
    spd = np.minimum(Chem.GetDistanceMatrix(mol), MAX_SPD + 1).astype(np.int64)
    nbrs, sign = chirality_reference(mol, pos)
    return {
        "lig_feat": torch.from_numpy(feat),
        "lig_bond": torch.from_numpy(bond),
        "lig_spd": torch.from_numpy(spd),
        "lig_pos": torch.from_numpy(pos),
        "chiral_nbrs": torch.from_numpy(nbrs.astype(np.int64)),
        "chiral_sign": torch.from_numpy(sign),
    }


# --------------------------------------------------------------------------------------
# Protein pocket
# --------------------------------------------------------------------------------------
def read_pdb(path: str | Path) -> dict[str, np.ndarray]:
    """Heavy atoms of standard (and common modified) residues from the first model of a PDB.

    Waters, ions, ligands, hydrogens and alternative locations other than the first are dropped.
    """
    pos, element, name, resname, resid = [], [], [], [], []
    with open(path) as f:
        for line in f:
            if line.startswith("ENDMDL"):
                break
            record = line[:6]
            if record not in ("ATOM  ", "HETATM"):
                continue
            res = line[17:20].strip()
            if record == "HETATM":
                if res not in MODIFIED_RESIDUES:
                    continue
                res = MODIFIED_RESIDUES[res]
            res = RESIDUE_ALIASES.get(res, res)
            if line[16] not in (" ", "A", "1"):
                continue
            atom_name = line[12:16].strip()
            elem = line[76:78].strip() or atom_name.lstrip("0123456789")[:1]
            elem = elem.capitalize()
            if elem in ("H", "D"):
                continue
            pos.append((float(line[30:38]), float(line[38:46]), float(line[46:54])))
            element.append(elem)
            name.append(atom_name)
            resname.append(res)
            resid.append(line[21:27])  # chain id + residue number + insertion code
    if not pos:
        raise ValueError(f"No protein atoms found in {path}")
    return {
        "pos": np.asarray(pos, dtype=np.float32),
        "element": np.asarray(element),
        "name": np.asarray(name),
        "resname": np.asarray(resname),
        "resid": np.asarray(resid),
    }


def _min_dist(protein: dict[str, np.ndarray], ref_pos: np.ndarray) -> np.ndarray:
    """Distance of every protein atom to the nearest reference point (Å)."""
    return np.linalg.norm(protein["pos"][:, None] - ref_pos[None], axis=-1).min(axis=1)


def pocket_center(
    protein: dict[str, np.ndarray], ref_pos: np.ndarray, com_cutoff: float = 6.0, dist: np.ndarray | None = None
) -> np.ndarray:
    """Centre of mass of the protein heavy atoms within ``com_cutoff`` Å of the reference.

    This is the centre the flow prior is built around, and it is a function of the protein and the
    reference only -- so training (reference = the bound ligand) and inference (a reference ligand,
    or an explicit centre) compute it the same way. The reference ligand's *own centroid* does not
    have that property: in re-docking training it is exactly the centroid of the answer, so the
    model never has to learn a translation, and then under-translates at inference where the centre
    is off by a few Å. On the ten example complexes this pocket CoM sits 1.7 Å (0.8-3.5 Å) away
    from the bound ligand's centroid, i.e. far enough to be a real translation to solve.

    A single reference point is taken at face value: it already is a stated pocket centre.
    """
    ref_pos = np.asarray(ref_pos, dtype=np.float32).reshape(-1, 3)
    if len(ref_pos) == 1:
        return ref_pos[0].copy()
    dist = _min_dist(protein, ref_pos) if dist is None else dist
    near = protein["pos"][dist < com_cutoff]
    return near.mean(axis=0) if len(near) else ref_pos.mean(axis=0)


def featurize_pocket(
    protein: dict[str, np.ndarray], ref_pos: np.ndarray, cutoff: float = 8.0, dist: np.ndarray | None = None
) -> dict[str, torch.Tensor]:
    """All heavy atoms of every residue with an atom within ``cutoff`` Å of the reference.

    Atoms come out grouped by residue, with the residues ordered by their distance to the
    reference; ``poc_res_id`` and ``poc_res_dmin`` record that grouping, and ``data.crop_pocket``
    uses them to narrow this to a budget when a complex is loaded.

    ``cutoff`` here is the *cache* radius, deliberately wider than the pocket that will be trained
    on, because the crop re-selects the shell against a randomly displaced reference and a residue
    that enters only under that displacement has to be in the cache to be selectable at all.
    """
    dist = _min_dist(protein, ref_pos) if dist is None else dist
    uniq, inv = np.unique(protein["resid"], return_inverse=True)
    inv = inv.ravel()
    res_dmin = np.full(len(uniq), np.inf, dtype=np.float32)
    np.minimum.at(res_dmin, inv, dist.astype(np.float32))

    kept = np.flatnonzero(res_dmin < cutoff)
    if kept.size == 0:
        raise ValueError(f"No protein residue within {cutoff} Å of the reference")
    kept = kept[np.argsort(res_dmin[kept], kind="stable")]  # nearest residue first
    rank = np.full(len(uniq), -1, dtype=np.int64)
    rank[kept] = np.arange(len(kept))
    atom_rank = rank[inv]  # -1 for atoms outside the pocket
    sel = np.flatnonzero(atom_rank >= 0)
    sel = sel[np.argsort(atom_rank[sel], kind="stable")]  # atoms grouped by residue

    feat = np.stack(
        [
            [_index(ELEMENTS, e) for e in protein["element"][sel]],
            [_index(ATOM_NAMES, n) for n in protein["name"][sel]],
            [_index(RESIDUES, r) for r in protein["resname"][sel]],
        ],
        axis=1,
    ).astype(np.int64)
    return {
        "poc_feat": torch.from_numpy(feat),
        "poc_pos": torch.from_numpy(protein["pos"][sel]),
        "poc_res_id": torch.from_numpy(atom_rank[sel]),  # [M] residue rank of each atom, ascending
        "poc_res_dmin": torch.from_numpy(res_dmin[kept]),  # [R] distance of each residue, ascending
    }


def featurize_complex(
    protein_pdb: str | Path,
    ligand: Chem.Mol,
    ref_pos: np.ndarray,
    pocket_cutoff: float = 12.0,
    com_cutoff: float = 6.0,
) -> dict[str, torch.Tensor]:
    """Ligand + pocket features. ``ref_pos`` (Å) defines the pocket and the prior centre.

    Re-docking: ``ref_pos`` is the ligand's own crystal pose. Cross-docking: a reference ligand, or
    a single point for an explicit pocket centre. ``pocket_cutoff`` is the *widest* shell ever
    needed: the pocket is narrowed to an atom budget by ``data.crop_pocket`` when a complex is
    loaded, so cache once with headroom and crop afterwards. ``ref_pos`` is kept in the item
    because the crop re-selects the shell against a displaced copy of it.
    """
    ref_pos = np.asarray(ref_pos, dtype=np.float32).reshape(-1, 3)
    protein = read_pdb(protein_pdb)
    dist = _min_dist(protein, ref_pos)
    out = featurize_ligand(ligand)
    out.update(featurize_pocket(protein, ref_pos, pocket_cutoff, dist))
    out["pocket_com"] = torch.from_numpy(pocket_center(protein, ref_pos, com_cutoff, dist))
    out["ref_pos"] = torch.from_numpy(ref_pos)
    out["poc_cache_cutoff"] = torch.tensor(float(pocket_cutoff))
    return out
